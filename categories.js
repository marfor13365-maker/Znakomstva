// Настраивает пару <select id="{fieldKey}_select"> + <input id="{fieldKey}_other">:
// заполняет список опциями, подставляет текущее значение из базы (если оно есть в
// списке — выбирает его; если нет — переключает на "Другое" и подставляет текст),
// показывает/скрывает поле "свой вариант" по выбору.
function blizkoInitCategoryField(fieldKey, options, currentValue) {
var select = document.getElementById(fieldKey + '_select');
var other = document.getElementById(fieldKey + '_other');
if (!select) return;
var optionsHtml = '<option value="">Не указано</option>';
options.forEach(function(o) {
optionsHtml += '<option value="' + o.replace(/"/g, '&quot;') + '">' + o + '</option>';
});
optionsHtml += '<option value="Другое">Другое (свой вариант)</option>';
select.innerHTML = optionsHtml;
var val = (currentValue || '').trim();
if (val && options.indexOf(val) !== -1) {
select.value = val;
if (other) other.style.display = 'none';
} else if (val) {
select.value = 'Другое';
if (other) { other.style.display = 'block'; other.value = val; }
} else {
select.value = '';
if (other) other.style.display = 'none';
}
if (other && !select.dataset.blizkoWired) {
select.dataset.blizkoWired = '1';
select.addEventListener('change', function() {
other.style.display = select.value === 'Другое' ? 'block' : 'none';
if (select.value !== 'Другое') other.value = '';
});
}
}

// Возвращает итоговое значение поля: либо выбранная категория, либо текст из "Другое".
function blizkoGetCategoryFieldValue(fieldKey) {
var select = document.getElementById(fieldKey + '_select');
var other = document.getElementById(fieldKey + '_other');
if (!select) return '';
if (select.value === 'Другое') return other ? other.value.trim() : '';
return select.value;
  }
